// Google Cloud TTS, using the existing gcloud login; no credentials are written to the repo.
// node scripts/generate-phonics-audio.cjs [--dry-run] [--only=sound:s] [--limit=1]
'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {execFileSync}=require('node:child_process');
const {createHash}=require('node:crypto');
const root=path.resolve(__dirname,'../phonics-lab'),ctx={window:{}};
for(const name of ['data.js','reading-data.js'])vm.runInNewContext(fs.readFileSync(path.join(root,name),'utf8'),ctx);
const D=ctx.window.PHONICS,R=ctx.window.PHONICS_READING;
const escape=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&apos;'}[c]));
const jobs=[];
function add(key,label,body,language='en-US'){jobs.push({key,label,language,voice:language==='en-US'?'en-US-Neural2-F':'ja-JP-Neural2-B',ssml:`<speak>${body}</speak>`,file:key.replaceAll(':','-')+'.mp3'});}
D.alphabet.forEach(l=>add('letter:'+l,l.toUpperCase()+' の名前',`<say-as interpret-as="characters">${l.toUpperCase()}</say-as>`));
// Do not synthesize isolated phonemes with SSML. A consonant-only override can
// silently fall back to the enclosed word or its letter name. Sound slots are
// reserved for teacher recordings until a validated isolated-sound source exists.
const words=new Map(D.sounds.flatMap(s=>s.examples.map(w=>[w.key,w.label])));
for(const w of [...R.words,...R.rules,...R.special])if(!words.has(w.key))words.set(w.key,w.key);
words.forEach((text,key)=>add('word:'+key,text,escape(text)));
D.vowels.forEach(v=>add('jp:'+v.id,v.kana,v.kana,'ja-JP'));
Object.entries(D.syllables).forEach(([c,row])=>D.vowels.forEach((v,i)=>add(`blend:${c}:${v.id}:joined`,row[i],row[i],'ja-JP')));
const arg=name=>process.argv.find(v=>v.startsWith('--'+name+'='))?.split('=').slice(1).join('=');
let selected=jobs.filter(j=>!arg('only')||j.key===arg('only'));
if(arg('limit'))selected=selected.slice(0,Number(arg('limit')));
if(!selected.length)throw new Error('No matching audio targets.');
if(process.argv.includes('--dry-run')){console.log(JSON.stringify({total:jobs.length,selected},null,2));process.exit(0);}
function gcloud(args){
 if(!args.every(v=>/^[a-z-]+$/.test(v)))throw new Error('Unexpected gcloud argument');
 const windows=process.platform==='win32';
 return execFileSync(windows?'cmd.exe':'gcloud',windows?['/d','/s','/c','gcloud '+args.join(' ')]:args,{encoding:'utf8',stdio:['ignore','pipe','pipe']}).trim();
}
async function main(){
 const dir=path.join(root,'assets/audio');fs.mkdirSync(dir,{recursive:true});
 const manifestPath=path.join(dir,'manifest.json');
 let manifest=fs.existsSync(manifestPath)?JSON.parse(fs.readFileSync(manifestPath,'utf8')):{provider:'Google Cloud Text-to-Speech',entries:{}};
 manifest.entries=Object.fromEntries(Object.entries(manifest.entries).filter(([key])=>!key.startsWith('sound:')));
 const publish=()=>{
  fs.writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n');
  const entries=Object.fromEntries(Object.entries(manifest.entries).map(([key,v])=>{const revision=createHash('sha256').update(fs.readFileSync(path.join(dir,v.file))).digest('hex').slice(0,12);return [key,{src:'assets/audio/'+v.file+'?v='+revision,voice:v.voice}];}));
  fs.writeFileSync(path.join(root,'audio-data.js'),'// Generated by scripts/generate-phonics-audio.cjs\nwindow.PHONICS_AUDIO = '+JSON.stringify(entries,null,2)+';\n');
 };
 if(process.argv.includes('--publish-only')){publish();return;}
 const project=process.env.GOOGLE_CLOUD_PROJECT||gcloud(['config','get-value','project']);
 const token=gcloud(['auth','print-access-token']);
 for(const job of selected){
  if(manifest.entries[job.key]?.ssml===job.ssml&&manifest.entries[job.key]?.voice===job.voice&&fs.existsSync(path.join(dir,job.file))){console.log('Exists '+job.key);continue;}
  const response=await fetch('https://texttospeech.googleapis.com/v1/text:synthesize',{method:'POST',headers:{Authorization:'Bearer '+token,'x-goog-user-project':project,'Content-Type':'application/json'},body:JSON.stringify({input:{ssml:job.ssml},voice:{languageCode:job.language,name:job.voice},audioConfig:{audioEncoding:'MP3',speakingRate:0.9}}),signal:AbortSignal.timeout(60000)});
  const result=await response.json();
  if(!response.ok)throw new Error('TTS '+response.status+': '+(result.error?.message||'request failed'));
  const bytes=Buffer.from(result.audioContent||'','base64');if(bytes.length<100)throw new Error('Empty audio: '+job.key);
  fs.writeFileSync(path.join(dir,job.file),bytes);
  manifest.entries[job.key]={...job,generated:new Date().toISOString(),bytes:bytes.length};publish();console.log('Generated '+job.key);
 }
 publish();console.log('Available '+Object.keys(manifest.entries).length+' / '+jobs.length);
}
main().catch(e=>{console.error(e.message);process.exitCode=1;});
