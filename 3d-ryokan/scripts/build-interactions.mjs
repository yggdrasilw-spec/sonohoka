import {readFileSync,writeFileSync} from 'node:fs';
import {BVHLoader} from '../vendor/BVHLoader.js';
import * as T from '../vendor/three.module.js';
const count=64,round=x=>+x.toFixed(6);
function capture(name,start,end,extract){
 const {skeleton,clip}=new BVHLoader().parse(readFileSync(new URL('./assets/'+name+'.bvh',import.meta.url),'utf8'));
 const root=skeleton.bones[0],mixer=new T.AnimationMixer(root);mixer.clipAction(clip).setLoop(T.LoopOnce,1).play();
 const p=n=>skeleton.bones.find(b=>b.name===n).getWorldPosition(new T.Vector3());
 return Array.from({length:count+1},(_,i)=>{
  mixer.setTime(T.MathUtils.lerp(start,end,i/count));root.updateMatrixWorld(true);
  const hip=p('Hips'),forward=p('LeftUpLeg').sub(p('RightUpLeg'));forward.y=0;forward.normalize().cross(new T.Vector3(0,1,0));
  const chest=p('Neck').sub(hip),lean=Math.atan2(chest.dot(forward),chest.y);
  return extract({p,hip,forward,lean});
 });
}
function normalizeProgress(frames,column){
 const first=frames[0][column],span=frames[count][column]-first;let previous=0;
 for(const f of frames){previous=Math.max(previous,T.MathUtils.clamp((f[column]-first)/span,0,1));f[column]=previous;}
 frames[0][column]=0;frames[count][column]=1;
}
function residual(frames,column,normalize=true){
 const start=frames[0][column],end=frames[count][column];
 frames.forEach((f,i)=>f[column]-=T.MathUtils.lerp(start,end,i/count));
 const max=Math.max(...frames.map(f=>Math.abs(f[column])),1e-6);
 if(normalize)frames.forEach(f=>f[column]/=max);
}
const reach=capture('15_06',.8,1.55,({p,hip,forward,lean})=>{
 const hand=p('RightHand').add(p('LeftHand')).multiplyScalar(.5).sub(hip);
 return [hand.dot(forward),hand.y,lean];
});
normalizeProgress(reach,0);residual(reach,1);
const initialLean=reach[0][2],leanSpan=reach[count][2]-initialLean;
reach.forEach(f=>f[2]=T.MathUtils.clamp((f[2]-initialLean)/leanSpan,0,1));
const lift=capture('115_01',1.2,1.85,({p,lean})=>[(p('RightHand').y+p('LeftHand').y)/2,lean]);
normalizeProgress(lift,0);normalizeProgress(lift,1);
const sit=capture('113_15',1.3,3.3,({hip,lean})=>[hip.y,lean]);
normalizeProgress(sit,0);residual(sit,1);sit.forEach(f=>f[1]=Math.max(0,f[1]));
const step={};
for(const [side,start,end] of [['Left',.45,.97],['Right',.89,1.36]]){
 const frames=capture('141_09',start,end,({p,lean})=>[p(side+'Foot').y,lean]);
 residual(frames,0);frames.forEach(f=>f[0]=Math.max(0,f[0]));residual(frames,1);
 step[side.toLowerCase()]=frames;
}
const data={reach,lift,sit,step};
writeFileSync(new URL('../models/interaction-clips.mjs',import.meta.url),'// Generated by scripts/build-interactions.mjs. CMU sources and license: models/README.md\nexport const interactionClips='+JSON.stringify(data,(_,x)=>typeof x==='number'?round(x):x)+';\n');
